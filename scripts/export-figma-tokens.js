#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

function exportTokens(format = 'css', outputPath = null) {
  const tokensPath = path.resolve(__dirname, '../templates/design-tokens/tokens.json');
  if (!fs.existsSync(tokensPath)) {
    console.error(`[Error] tokens.json not found at ${tokensPath}`);
    process.exit(1);
  }

  const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf-8'));
  let output = '';

  if (format === 'css') {
    output += '/* Generated by Design UX Ultra Token Engine */\n:root {\n';
    // Primitives
    const colors = tokens.primitives.color;
    for (const [family, shades] of Object.entries(colors)) {
      for (const [shade, data] of Object.entries(shades)) {
        output += `  --primitive-${family}-${shade}: ${data.value};\n`;
      }
    }
    // Radii
    for (const [rKey, rData] of Object.entries(tokens.primitives.radius)) {
      output += `  --radius-${rKey}: ${rData.value};\n`;
    }
    output += '}\n';
  } else if (format === 'json') {
    output = JSON.stringify(tokens, null, 2);
  } else {
    console.error(`[Error] Unsupported format: ${format}. Use "css" or "json".`);
    process.exit(1);
  }

  if (outputPath) {
    fs.writeFileSync(outputPath, output, 'utf-8');
    console.log(`\x1b[32m✔ Exported tokens (${format}) to: ${outputPath}\x1b[0m`);
  } else {
    console.log(output);
  }
}

module.exports = { exportTokens };

if (require.main === module) {
  const args = process.argv.slice(2);
  const format = args[0] || 'css';
  const out = args[1] || null;
  exportTokens(format, out);
}
